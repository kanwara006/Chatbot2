export async function simulateAIResponse(question: string): Promise<{
  answer: string
  sources: MessageSource[]
}> {
  // จำลอง network delay (1.5–2.5 วินาที)
  const delay = 1500 + Math.random() * 1000
  await new Promise((r) => setTimeout(r, delay))

  const lower = question.toLowerCase()

  for (const item of keywordResponses) {
    if (item.keywords.some((kw) => lower.includes(kw))) {
      return { answer: item.answer, sources: item.sources }
    }
  }

  return mockResponses.default
}

// ── Conversation Storage ─────────────────────────────────────────────

export function getStoredConversations(): Conversation[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    return raw ? JSON.parse(raw) : []
  } catch {
    return []
  }
}

export function saveConversation(conv: Conversation): void {
  const convs = getStoredConversations()
  const idx = convs.findIndex((c) => c.id === conv.id)
  if (idx >= 0) {
    convs[idx] = conv
  } else {
    convs.unshift(conv)
  }
  localStorage.setItem(STORAGE_KEY, JSON.stringify(convs))
}

export function deleteConversation(id: number): void {
  const convs = getStoredConversations().filter((c) => c.id !== id)
  localStorage.setItem(STORAGE_KEY, JSON.stringify(convs))
}

export function generateId(): number {
  return Date.now() + Math.floor(Math.random() * 1000)
}
